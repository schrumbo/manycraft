    /// The icon as SVG for `size` px, its outline drawn `stroke` px wide.
    pub fn svg(self, stroke: f32, size: f32) -> Bytes {
        Bytes::from(format!(r#"<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="{}" stroke-linecap="round" stroke-linejoin="round">{}</svg>"#, stroke * 24. / size, self.lucide()))
    }
